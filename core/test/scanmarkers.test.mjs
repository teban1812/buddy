import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { skipMarker } from '../src/scan.mjs';

// The words are assembled so that this file does not contain the markers it tests: the scan reads test files too and makes no exception.
const SK = 'it.' + 'skip(', LINT = 'eslint-' + 'disable', NV = '--no-' + 'verify', TS = '@ts-' + 'ignore';

test('a skipped test, a silenced check or a switched-off hook is a marker wherever it is written: code, comment, test or pattern', () => {
  for (const line of [`  ${SK}'works', () => {});`, `// ${LINT}-next-line no-unused-vars`, `git commit ${NV}`, `# a comment that says ${NV}`, `/* ${TS} */`, `// ${SK} was here`])
    assert.equal(skipMarker(line), true, line);
});
test('ordinary lines are not markers', () => {
  for (const line of ['it(\'works\', () => {});', 'const skipped = items.filter(Boolean);', '// verify the hook runs', 'git commit -m "x"']) assert.equal(skipMarker(line), false, line);
});
test('the scan can read its own source and its tests: none of them contains a marker', () => {
  for (const f of ['../src/scan.mjs', './scanmarkers.test.mjs']) {
    const lines = fs.readFileSync(fileURLToPath(new URL(f, import.meta.url)), 'utf8').split('\n');
    assert.deepEqual(lines.filter(skipMarker), [], f);
  }
});

import { analyse } from '../src/scan.mjs';
const patch = (file, lines) => [`diff --git a/${file} b/${file}`, `--- a/${file}`, `+++ b/${file}`, '@@ -1 +1 @@', ...lines];
test('a line one commit of the slice added and a later one removed is not part of its work (it is not judged)', () => {
  const sc = analyse([{ status: 'M', file: 'src/a.js' }, { status: 'M', file: 'src/a.test.js' }], [
    ...patch('src/a.js', [`+// ${NV} here`, '+keep();']), ...patch('src/a.test.js', ["+assert.equal(1, 1);", "-assert.equal(2, 2);"]),
    ...patch('src/a.js', [`-// ${NV} here`]), ...patch('src/a.test.js', ["-assert.equal(1, 1);", "+assert.equal(1, 1);"]),
  ], 'r');
  assert.deepEqual(sc.skip_markers_added, []); assert.equal(sc.assertions_removed, 1); assert.equal(sc.assertions_added, 1);
  assert.deepEqual(sc.modified_existing_tests, ['src/a.test.js (-1 lines)']);
  const stays = analyse([{ status: 'M', file: 'src/a.js' }], patch('src/a.js', [`+// ${NV} here`]), 'r');
  assert.deepEqual(stays.skip_markers_added, [`src/a.js: // ${NV} here`]);
});

const PRAGMA = '#pra' + 'gma warning dis' + 'able 612, 618';
test('files a tool generates are exempt from the skip-marker rule by path and name, and the scan lists them; a hand-written file is not', () => {
  const generated = ['Data/Migrations/20261104_AddBooks.cs', 'Data/Migrations/20261104_AddBooks.Designer.cs', 'Data/AppDbContextModelSnapshot.cs', 'Forms/Main.Designer.cs',
    'obj/Views/Home.g.cs', 'obj/App.g.i.cs', 'src/api.generated.ts'];
  const hand = ['src/Hand.cs', 'src/Marked.cs', 'src/Migrations.cs', 'src/generated.cs'];
  const sc = analyse([...generated, ...hand].map(file => ({ status: 'A', file })), [
    ...generated.flatMap(f => patch(f, [`+${PRAGMA}`])), ...patch(hand[0], [`+${PRAGMA}`]),
    ...patch(hand[1], ['+// <auto-generated />', `+${PRAGMA}`]),   // a hand-written file that claims to be generated: the marker alone exempts nothing
    ...patch(hand[2], [`+${PRAGMA}`]), ...patch(hand[3], [`+${PRAGMA}`]),
  ], 'r');
  assert.deepEqual(sc.skipped_generated, generated);
  assert.deepEqual(sc.skip_markers_added, hand.map(f => `${f}: ${PRAGMA}`));
  assert.equal(sc.flagged, true);
});
